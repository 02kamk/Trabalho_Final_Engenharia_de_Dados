# MAGIC %md
# MAGIC ## Criação das tabelas
# MAGIC
# MAGIC `sk` é uma coluna de identidade: o Delta gera o número na inserção. `BY DEFAULT` permite gravar o
# MAGIC membro desconhecido com `sk = -1`. `hash_atributos` guarda o hash dos atributos rastreados, para
# MAGIC detectar mudanças sem comparar coluna por coluna.

# COMMAND ----------

COLUNAS_SCD = """
    data_inicio     TIMESTAMP NOT NULL,
    data_fim        TIMESTAMP NOT NULL,
    registro_atual  BOOLEAN   NOT NULL,
    hash_atributos  STRING
"""

spark.sql(f"""
    CREATE TABLE IF NOT EXISTS {SCHEMA_GOLD}.dim_municipio (
        sk_municipio  BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
        ibge          STRING,
        nome          STRING,
        fonte         STRING,
        data_coleta   DATE,
        {COLUNAS_SCD}
    ) USING DELTA
""")

spark.sql(f"""
    CREATE TABLE IF NOT EXISTS {SCHEMA_GOLD}.dim_funcao (
        sk_funcao     BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
        codigo        SMALLINT,
        nome          STRING,
        area          STRING,
        {COLUNAS_SCD}
    ) USING DELTA
""")

spark.sql(f"""
    CREATE TABLE IF NOT EXISTS {SCHEMA_GOLD}.dim_elemento_despesa (
        sk_elemento    BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
        codigo         STRING,
        nome           STRING,
        grupo_despesa  STRING,
        {COLUNAS_SCD}
    ) USING DELTA
""")


def garantir_membro_desconhecido(tabela, sk, valores):
    """Insere a linha sk = -1 ("Não informada") se ela ainda não existir."""
    if spark.table(tabela).where(F.col(sk) == -1).limit(1).count():
        return
    colunas = ", ".join([sk, *valores, "data_inicio", "data_fim", "registro_atual", "hash_atributos"])
    literais = ", ".join(["-1", *valores.values(),
                          f"TIMESTAMP'{INICIO_VALIDADE}'", f"TIMESTAMP'{FIM_VALIDADE}'", "true", "NULL"])
    spark.sql(f"INSERT INTO {tabela} ({colunas}) VALUES ({literais})")


garantir_membro_desconhecido(f"{SCHEMA_GOLD}.dim_funcao", "sk_funcao",
                             {"codigo": "NULL", "nome": "'Não informada'", "area": "'Não informada'"})
garantir_membro_desconhecido(f"{SCHEMA_GOLD}.dim_elemento_despesa", "sk_elemento",
                             {"codigo": "NULL", "nome": "'Não informado'", "grupo_despesa": "'Outros'"})

# COMMAND ----------

# MAGIC %md
# MAGIC ## SCD tipo 2 com MERGE
# MAGIC
# MAGIC Padrão do Delta Lake: as linhas da Silver entram duas vezes no MERGE quando um atributo mudou.
# MAGIC
# MAGIC - Com `_chave_merge` = chave natural: casam com a versão atual e a **fecham**.
# MAGIC - Com `_chave_merge` = nulo: não casam com nada e são **inseridas** como a nova versão.
# MAGIC
# MAGIC Chaves novas entram só uma vez e são inseridas com validade desde 1900-01-01.

# COMMAND ----------

def hash_atributos(atributos):
    return F.sha2(F.concat_ws("||", *[F.coalesce(F.col(a).cast("string"), F.lit("∅")) for a in atributos]), 256)


def aplicar_scd2(tabela, origem, chave, atributos):
    """Aplica as linhas de `origem` (chave, atributos, atualizado_em) na dimensão `tabela`."""
    origem = origem.withColumn("hash_atributos", hash_atributos(atributos))
    atual = spark.table(tabela).where(F.col("registro_atual") & F.col(chave).isNotNull())

    alteradas = (
        origem.alias("o")
        .join(atual.alias("a"), F.col(f"o.{chave}") == F.col(f"a.{chave}"))
        .where(F.col("o.hash_atributos") != F.col("a.hash_atributos"))
        .select("o.*")
    )
    qtd_alteradas = alteradas.count()  # antes do MERGE: depois dele, os hashes já são iguais

    preparadas = (
        origem
        .withColumn("_chave_merge", F.col(chave))
        .withColumn("_inicio", F.to_timestamp(F.lit(INICIO_VALIDADE)))
        .unionByName(
            alteradas
            .withColumn("_chave_merge", F.lit(None).cast(origem.schema[chave].dataType))
            .withColumn("_inicio", F.col("atualizado_em"))
        )
    )

    inserir = {c: f"novo.{c}" for c in [chave, *atributos, "hash_atributos"]}
    inserir.update({
        "data_inicio": "novo._inicio",
        "data_fim": f"TIMESTAMP'{FIM_VALIDADE}'",
        "registro_atual": "true",
    })

    (
        DeltaTable.forName(spark, tabela).alias("dim")
        .merge(preparadas.alias("novo"), f"dim.{chave} = novo._chave_merge AND dim.registro_atual")
        .whenMatchedUpdate(
            condition="dim.hash_atributos <> novo.hash_atributos",
            set={"registro_atual": "false", "data_fim": "novo.atualizado_em"},
        )
        .whenNotMatchedInsert(values=inserir)
        .execute()
    )

    versoes = spark.table(tabela).where(F.col(chave).isNotNull())
    print(f"{tabela:<45} {versoes.where('registro_atual').count():>4} chaves  "
          f"{versoes.count():>4} versões  ({qtd_alteradas} alterada(s) nesta execução)")

