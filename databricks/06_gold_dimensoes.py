# MAGIC %md
# MAGIC # Gold: dimensões (SCD tipo 2)
# MAGIC
# MAGIC Issues #16 e #17. Lê a Silver e grava as dimensões do modelo dimensional no schema
# MAGIC `workspace.amrec_gold`. O modelo está descrito em `docs/gold.md`.
# MAGIC
# MAGIC | Dimensão | Chave natural | Atributos | Origem |
# MAGIC | --- | --- | --- | --- |
# MAGIC | `dim_municipio` | `ibge` | nome, fonte, data_coleta | `silver.municipio` |
# MAGIC | `dim_funcao` | `codigo` | nome, area | `silver.funcao` |
# MAGIC | `dim_elemento_despesa` | `codigo` | nome, grupo_despesa | `silver.elemento_despesa` + `referencia/elemento_grupo.csv` |
# MAGIC | `dim_data` | `data` | ano, mês, trimestre | gerada aqui, sem SCD |
# MAGIC
# MAGIC **SCD tipo 2:** cada dimensão tem `data_inicio`, `data_fim` e `registro_atual`. Quando um atributo muda
# MAGIC na origem, a versão atual é fechada (`data_fim` = momento da alteração, `registro_atual` = falso) e uma
# MAGIC nova versão é inserida. A primeira versão de cada chave vale desde 1900-01-01, para que os fatos
# MAGIC anteriores à primeira carga encontrem uma versão.
# MAGIC
# MAGIC **Membro desconhecido:** `dim_funcao` e `dim_elemento_despesa` têm a linha `sk = -1` ("Não informada"),
# MAGIC usada pelos empenhos sem função (todo o Atende.net) ou sem elemento.
# MAGIC
# MAGIC As dimensões são pequenas (12, 28 e 50 linhas), então cada execução compara a Silver inteira com a
# MAGIC versão atual de cada chave. Reexecutar sem mudanças na origem não altera nada.

# COMMAND ----------

from delta.tables import DeltaTable
from pyspark.sql import functions as F

CATALOGO = "workspace"
SCHEMA_SILVER = f"{CATALOGO}.amrec_silver"
SCHEMA_GOLD = f"{CATALOGO}.amrec_gold"
VOLUME_REFERENCIA = f"/Volumes/{CATALOGO}/amrec/referencia"

INICIO_VALIDADE = "1900-01-01 00:00:00"
FIM_VALIDADE = "9999-12-31 00:00:00"

# Áreas do dashboard, pelo código nacional da função (Portaria MOG 42/1999).
AREAS = {4: "Administração", 10: "Saúde", 12: "Educação", 15: "Urbanismo"}

# Grupo de natureza de despesa (2º dígito da natureza) → rótulo usado no dashboard.
# Juros (2), inversões (5) e amortização (6) ficam em "Outros".
GRUPOS = {"1": "Pessoal", "3": "Custeio", "4": "Investimento"}

spark.sql(f"CREATE SCHEMA IF NOT EXISTS {SCHEMA_GOLD}")

