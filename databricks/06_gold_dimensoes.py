# MAGIC %md
# MAGIC ## Conferência
# MAGIC
# MAGIC Cada chave natural deve ter exatamente uma versão atual, e as versões de uma chave não podem se
# MAGIC sobrepor no tempo.

# COMMAND ----------

DIMENSOES_SCD = [
    ("dim_municipio", "ibge", "sk_municipio"),
    ("dim_funcao", "codigo", "sk_funcao"),
    ("dim_elemento_despesa", "codigo", "sk_elemento"),
]
for tabela, chave, sk in DIMENSOES_SCD:
    dim = spark.table(f"{SCHEMA_GOLD}.{tabela}").where(F.col(chave).isNotNull())
    atuais_por_chave = dim.groupBy(chave).agg(F.sum(F.col("registro_atual").cast("int")).alias("atuais"))
    erradas = atuais_por_chave.where("atuais <> 1").count()
    sobrepostas = (
        dim.alias("a").join(dim.alias("b"), chave)
        .where((F.col(f"a.{sk}") != F.col(f"b.{sk}"))
               & (F.col("a.data_inicio") < F.col("b.data_fim"))
               & (F.col("b.data_inicio") < F.col("a.data_fim")))
        .count()
    )
    if erradas or sobrepostas:
        raise ValueError(f"{tabela}: {erradas} chave(s) sem exatamente uma versão atual, "
                         f"{sobrepostas} par(es) de versões sobrepostas")

display(
    spark.table(f"{SCHEMA_GOLD}.dim_elemento_despesa")
    .where("registro_atual")
    .groupBy("grupo_despesa").count()
    .orderBy("grupo_despesa")
)
